// Generates db/reference.sql: the reference data a PRODUCTION database needs — cities and their localities with
// reference prices (sale rate, rent rate, yearly growth, coordinates). Nothing else: no demo listings, projects,
// builders, people, reviews or leads.
//
// Safe on an empty or a live database: every row is INSERT … ON CONFLICT DO NOTHING (existing rows are left as
// they are) and the file never deletes or updates anything. Run after the migrations:
//   npm run db:reference:build && npm run db:reference:remote
// The demo seed (db/seed.sql) stays local-only. See DEPLOY.md.
// Run: node db/build-reference.ts   (Node 22.18+/24 strips TypeScript types natively)
import { writeFileSync } from 'node:fs';
import { cities, localities } from './seed-data.ts';

const q = (v: unknown): string => (typeof v === 'number' ? (Number.isFinite(v) ? String(v) : 'NULL') : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table: string, cols: string[], rows: unknown[][]) =>
  rows.length ? `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${rows.map((r) => `(${r.map(q).join(', ')})`).join(',\n')}\nON CONFLICT DO NOTHING;\n` : '';

const out = [
  '-- Generated by db/build-reference.ts — do not edit by hand.',
  '-- Reference data only (cities, localities, reference prices). Inserts missing rows; never deletes or updates.',
  insert('cities', ['slug', 'name', 'state', 'stamp_duty_pct', 'lat', 'lng', 'sort_order'],
    cities.map((c, i) => [c.slug, c.name, c.state, c.stampDutyPct, c.lat, c.lng, i])),
  insert('localities', ['city_slug', 'slug', 'name', 'rate_per_sqft', 'rent_per_sqft', 'yoy_growth_pct', 'lat', 'lng'],
    localities.map((l) => [l.citySlug, l.slug, l.name, l.ratePerSqft, l.rentPerSqft, l.yoyGrowthPct, +l.lat.toFixed(5), +l.lng.toFixed(5)])),
].join('\n');

writeFileSync(new URL('./reference.sql', import.meta.url), out);
console.log(`reference.sql: ${cities.length} cities, ${localities.length} localities (no listings, projects, builders, people or reviews)`);
